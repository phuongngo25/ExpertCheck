class AdvancedDataProcessor:
    def __init__(self, config):
        self.config = config
        self.logger = logging.getLogger(__name__)
        self.proc_config = config.wyo_processing

    def process_dataframe(self, df: pd.DataFrame) -> pd.DataFrame:
        self.logger.info(f"Bắt đầu xử lý DataFrame có {len(df)} dòng.")
        emg_cols = [f'emg_{i+1}' for i in range(self.proc_config.max_channels)]
        
        # Bước 1: Làm sạch dữ liệu
        initial_rows = len(df)
        df.replace([np.inf, -np.inf], np.nan, inplace=True)
        df.dropna(subset=emg_cols + ['label', 'participant'], inplace=True)
        z_scores = np.abs(stats.zscore(df[emg_cols]))
        df = df[(z_scores < 3.0).all(axis=1)]
        rows_removed = initial_rows - len(df)
        self.logger.info(f"...bước 1: Đã làm sạch dữ liệu, loại bỏ {rows_removed} dòng.")

        if df.empty:
            return df

        self.logger.info("...bước 2: Áp dụng bộ lọc FIR (khuếch đại)")
        filtered_emg_data = self._apply_fir_filters(df[emg_cols].values)
        df[emg_cols] = filtered_emg_data
        
        self.logger.info("...bước 3: Tái chuẩn hóa tín hiệu (Z-score)")
        normalized_emg_data = self._normalize_data(df[emg_cols].values)
        df[emg_cols] = normalized_emg_data
        
        self.logger.info(f"Tiền xử lý hoàn tất. DataFrame cuối cùng có {len(df)} dòng.")
        return df

    def _apply_fir_filters(self, data: np.ndarray) -> np.ndarray:
        filtered_data = np.zeros_like(data)
        for ch in range(data.shape[1]):

            notch_output = signal.lfilter(NOTCH_COEFFS_RAW, 1.0, data[:, ch])
            bandpass_output = signal.lfilter(BANDPASS_COEFFS_RAW, 1.0, notch_output)
            filtered_data[:, ch] = bandpass_output
        return filtered_data
        
    def _normalize_data(self, data: np.ndarray) -> np.ndarray:
        # Chuẩn hóa Z-score trên toàn bộ dữ liệu
        mean = np.mean(data, axis=0)
        std = np.std(data, axis=0)
        # Tránh chia cho 0 nếu một kênh tín hiệu không đổi
        std[std == 0] = 1
        return (data - mean) / std